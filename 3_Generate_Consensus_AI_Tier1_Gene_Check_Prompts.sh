#!/bin/bash

###-----------------------------------------------------------------------------###
###
### 3_Generate_Consensus_AI_Tier1_Gene_Check_Prompts.sh
###
###-----------------------------------------------------------------------------###
###
### Reads Tier1_genes_AD_Cancer_Pub.txt (tab-delimited, 6 columns:
###   1=GENE_Symbol  2=Category  3=Tier  4=Cancer_Patho_PubMed_IDs  5=AD_Patho_PubMed_IDs
###	  6=Statements)
### and writes one plain-text prompt file per gene into OUTDIR,
### substituting {GENE_SYMBOL}, {CANCER_PMIDS}, {AD_PMIDS}, and {Statements}
###
### This file is also saved in the Supplemental Table 1 without Category or Tier columns
###
### To run this script, please execute the following line in the shell
### ./3_Generate_Consensus_AI_Tier1_Gene_Check_Prompts.sh Teir1_genes_AD_Cancer_Pub.txt Tier1_check_prompts
###
### Teir1_genes_AD_Cancer_Pub.txt is the reference file
### "Tier1_check_prompts" is the folder name to store the prompts generated by this script
###
###-----------------------------------------------------------------------------###

set -euo pipefail

INPUT_FILE="${1:-Teir1_genes_AD_Cancer_Pub.txt}"
OUTDIR="${2:-Tier1_check_prompts}"

mkdir -p "$OUTDIR"

# Skip the header line, then process each row.
# IFS=tab so $1, $2, $4 map directly to the needed columns.
tail -n +2 "$INPUT_FILE" | while IFS=$'\t' read -r  GENE_SYMBOL Category  Tier  Cancer_Patho_PubMed_IDs  AD_Patho_PubMed_IDs Statements || [ -n "${GENE_SYMBOL:-}" ]; do

    # Skip any blank lines
    [ -z "$GENE_SYMBOL" ] && continue

    OUTFILE="${OUTDIR}/${GENE_SYMBOL}_DB_Check_query.txt"

    cat > "$OUTFILE" <<EOF
	I am investigating the inverse or shared-risk relationship of the ${GENE_SYMBOL} gene's pathological role between cancer and Alzheimer's disease (AD). 
	I found Cancer-related PubMed ID(s) (${Cancer_Patho_PubMed_IDs}) and AD-related PubMed ID(s) (${AD_Patho_PubMed_IDs}) that discuss the gene's pathological role in cancer and AD, respectively. 
	
	Please strictly check the content of the listed publications. Do not use any external knowledge or information beyond what these publications state. 
	Determine if the following statement is totally true; mostly true; partially true; totally false; or not verifiable.

	Statement: ${Statements}

EOF
    echo "Wrote: $OUTFILE"
done

echo "Done. Files written to: $OUTDIR"


