#!/bin/bash

###-----------------------------------------------------------------------------###
###
### 2_Generate_Claude_AI_Gene_Check_Prompts
###
### Reads PubMed_for_AD_and_Cancer.txt (tab-delimited, 5 columns:
###   1=GENE_SYMBOL  2=CANCER_PMIDs  3=CANCER_N  4=AD_PMIDs  5=AD_N)
### and writes one plain-text prompt file per gene into OUTDIR,
### substituting {GENE_SYMBOL}, {CANCER_PMIDS}, and {AD_PMIDS}
###
### To run this script, please execute the following line on the shell
### ./generate_gene_prompts.sh PubMed_for_AD_and_Cancer.txt gene_prompts
### PubMed_for_AD_and_Cancer.txt is the reference file
### "gene_prompts" is the folder name to store the prompts generated by this script
###
###-----------------------------------------------------------------------------###

set -euo pipefail

INPUT_FILE="${1:-PubMed_for_AD_and_Cancer.txt}"
OUTDIR="${2:-gene_prompts}"

mkdir -p "$OUTDIR"

# Skip the header line, then process each row.
# IFS=tab so $1, $2, $4 map directly to the needed columns.
tail -n +2 "$INPUT_FILE" | while IFS=$'\t' read -r GENE_SYMBOL CANCER_PMIDS CANCER_N AD_PMIDS AD_N; do

    # Skip any blank lines
    [ -z "$GENE_SYMBOL" ] && continue

    OUTFILE="${OUTDIR}/${GENE_SYMBOL}_AI_query.txt"

    cat > "$OUTFILE" <<EOF
	You are assisting a geneticist and research faculty member at a university who is investigating the inverse or shared-risk relationship of a gene's pathological role between cancer and Alzheimer's disease (AD).

	Gene of interest: ${GENE_SYMBOL}
	Cancer-related PubMed ID(s): ${CANCER_PMIDS}
	AD-related PubMed ID(s): ${AD_PMIDS}

	Instructions: Base your answers strictly on the content of the listed publications. Do not use any external knowledge or information beyond what these publications state. Answer the following questions in order, skipping sub-questions as directed.

	1. Do all of the cancer publications (PMIDs: ${CANCER_PMIDS}) describe ${GENE_SYMBOL}'s pathological role in cancer?
	   Answer: Yes or No.
	   - If Yes, skip 1a and 1b.
	   - If No, proceed to 1a.

	   1a. Does at least one of these publications describe ${GENE_SYMBOL}'s pathological role in cancer?
	       Answer: Yes or No.
	       - If No, skip 1b.
	       - If Yes, proceed to 1b.

	   1b. How many of the publications describe this role? And what are the PubMed ID(s)?

	2. Do all of the AD publications (PMIDs: ${AD_PMIDS}) describe ${GENE_SYMBOL}'s pathological role in AD?
	   Answer: Yes or No.
	   - If Yes, skip 2a and 2b.
	   - If No, proceed to 2a.

	   2a. Does at least one of these publications describe ${GENE_SYMBOL}'s pathological role in AD?
	       Answer: Yes or No.
	       - If No, skip 2b.
	       - If Yes, proceed to 2b.

	   2b. How many of the publications describe this role? And what are the PubMed ID(s)?

	3. Using only the publications that describe ${GENE_SYMBOL}'s pathological role, summarize its role in cancer in 3–5 sentences and its role in AD in 3–5 sentences (two separate summaries).

	4. If the answer to (1) or (1a) is Yes, AND the answer to (2) or (2a) is Yes: do cancer and AD share the same metabolic pathway or pathology involving ${GENE_SYMBOL}?
	   Answer: Yes or No.
	   - If No, skip 4a and 4b.

	   4a. What is the name of the shared pathway or pathology?

	   4b. Does ${GENE_SYMBOL} act differently in cancer versus AD (for example, through opposing regulation such as up-regulation in cancer versus down-regulation in AD, or through a different mechanism entirely, such as distinct downstream targets, binding partners, or cellular pathways)? Summarize in 3–5 sentences.
	
	Output format: Return your answers as a tab-delimited plain text file with exactly 10 columns, in this order, using the following header row:
	1	1a	1b	2	2a	2b	3	4	4a	4b

	For any skipped question, leave the corresponding cell blank (do not write "N/A" or "skipped"). Ensure all text within a single cell (e.g., multi-sentence summaries) does not contain tab or newline characters, so the file remains correctly delimited. Save the file as: ${GENE_SYMBOL}_CADIC_Result.txt

EOF
    echo "Wrote: $OUTFILE"
done

echo "Done. Files written to: $OUTDIR"
